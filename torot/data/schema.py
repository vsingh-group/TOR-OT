"""Hugging Face dataset schema for OT instances (one record per instance, sparse plan)."""

from __future__ import annotations

from datasets import ClassLabel, Features, Sequence, Value

from torot.data.cost import COST_TYPES

FEATURES = Features(
    {
        "n": Value("int32"),                                   # number of source bins
        "m": Value("int32"),                                   # number of target bins
        "dim": Value("int32"),                                 # support dimension (1 or 2)
        "cost_type": ClassLabel(names=list(COST_TYPES)),
        "family_src": Value("string"),
        "family_tgt": Value("string"),
        "coords_src": Sequence(Sequence(Value("float64"))),    # [n, dim], canonical order
        "coords_tgt": Sequence(Sequence(Value("float64"))),    # [m, dim], canonical order
        "a": Sequence(Value("float64")),                       # source marginal, sums to 1
        "b": Sequence(Value("float64")),                       # target marginal, sums to 1
        "plan_rows": Sequence(Value("int32")),                 # COO of POT's optimal plan
        "plan_cols": Sequence(Value("int32")),
        "plan_vals": Sequence(Value("float64")),
        "ot_cost": Value("float64"),                           # <C, plan> with C max-normalised
        "seed": Value("int64"),                                # per-instance RNG seed
    }
)

